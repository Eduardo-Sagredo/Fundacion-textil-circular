CREATE TABLE chats (
                       chat_id         VARCHAR2(150 CHAR) PRIMARY KEY,
                       cerrado         NUMBER(1)          DEFAULT 0 NOT NULL,
                       fecha_creacion  TIMESTAMP          DEFAULT CURRENT_TIMESTAMP NOT NULL,
                       CONSTRAINT chk_chats_cerrado CHECK (cerrado IN (0, 1))
);

CREATE TABLE mensajes (
                          id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          chat_id         VARCHAR2(150 CHAR)  NOT NULL,
                          contenido       VARCHAR2(1000 CHAR) NOT NULL,
                          es_de_usuario   NUMBER(1)           NOT NULL,
                          leido           NUMBER(1)           DEFAULT 0 NOT NULL,
                          fecha_envio     TIMESTAMP           DEFAULT CURRENT_TIMESTAMP NOT NULL,
                          CONSTRAINT fk_mensajes_chat     FOREIGN KEY (chat_id) REFERENCES chats (chat_id) ON DELETE CASCADE,
                          CONSTRAINT chk_mensajes_usuario CHECK (es_de_usuario IN (0, 1)),
                          CONSTRAINT chk_mensajes_leido   CHECK (leido IN (0, 1))
);

CREATE INDEX idx_mensajes_chat_fecha ON mensajes (chat_id, fecha_envio);