CREATE TABLE productos (
                           id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           nombre          VARCHAR2(150 CHAR)  NOT NULL,
                           descripcion     VARCHAR2(1000 CHAR) NOT NULL,
                           precio          NUMBER(10, 2)       NOT NULL,
                           categoria       VARCHAR2(80 CHAR)   NOT NULL,
                           imagen_url      VARCHAR2(500 CHAR),
                           disponible      NUMBER(1)           DEFAULT 1 NOT NULL,
                           usuario_id      NUMBER(19),
                           fecha_creacion  TIMESTAMP           DEFAULT CURRENT_TIMESTAMP NOT NULL,
                           CONSTRAINT chk_productos_precio     CHECK (precio >= 0),
                           CONSTRAINT chk_productos_disponible CHECK (disponible IN (0, 1))
);

CREATE INDEX idx_productos_categoria ON productos (categoria);
CREATE INDEX idx_productos_usuario   ON productos (usuario_id);