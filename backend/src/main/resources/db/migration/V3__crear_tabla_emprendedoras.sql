CREATE TABLE emprendedoras (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    rut VARCHAR2(20 CHAR) NOT NULL,
    nombre VARCHAR2(150 CHAR) NOT NULL,
    correo VARCHAR2(150 CHAR) NOT NULL,
    contrasena VARCHAR2(255 CHAR) NOT NULL,

    nombre_emprendimiento VARCHAR2(150 CHAR) NOT NULL,
    rubro VARCHAR2(120 CHAR) NOT NULL,

    region VARCHAR2(120 CHAR) NOT NULL,
    comuna VARCHAR2(120 CHAR) NOT NULL,

    edad NUMBER(3) NOT NULL,
    genero VARCHAR2(50 CHAR) NOT NULL,

    rol VARCHAR2(30 CHAR) DEFAULT 'EMPRENDEDORA' NOT NULL,
    estado VARCHAR2(20 CHAR) DEFAULT 'PENDIENTE' NOT NULL,

    motivo_rechazo VARCHAR2(500 CHAR),

    CONSTRAINT uk_emprendedoras_rut UNIQUE (rut),
    CONSTRAINT uk_emprendedoras_correo UNIQUE (correo),

    CONSTRAINT chk_emprendedoras_estado
        CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA'))
);